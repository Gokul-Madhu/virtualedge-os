#!/usr/bin/env python3
"""Automated QEMU serial boot + guest self-test; no extra Python modules.

Runs with a disposable copy of the rootfs. Requires Linux/WSL, qemu-system-aarch64,
and images generated by scripts/build-and-test.sh.
"""
import argparse
import errno
import os
from pathlib import Path
import pty
import re
import select
import shutil
import signal
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
IMAGES = ROOT / 'out/buildroot/images'
QEMU_HOST = ROOT / 'out/buildroot/host/bin/qemu-system-aarch64'

# Recognizable boot failures must stop acceptance immediately instead of
# consuming the full per-boot timeout and obscuring the actual kernel error.
BOOT_FAILURE_MARKERS = (
    'Kernel panic - not syncing:',
    'VFS: Unable to mount root fs',
    'No working init found',
    'Requested init',
)

def check_boot_failure(serial_output):
    """Raise on a definitive Linux startup failure (never accept a later echo)."""
    for marker in BOOT_FAILURE_MARKERS:
        if marker in serial_output:
            raise RuntimeError(f'ARM64 guest kernel boot failure: {marker}; inspect serial output above')



def verify_cmdline(console_text, expected_slot, expected_version):
    """Validate guest-reported boot arguments, not a host-only selection guess."""
    matches = re.findall(r'(?m)^([^\r\n]*ve\.slot=[AB][^\r\n]*)\r?$', console_text)
    if len(matches) != 1:
        raise RuntimeError('Missing or ambiguous guest /proc/cmdline slot evidence')
    words = matches[0].split()
    if f've.slot={expected_slot}' not in words or f've.version={expected_version}' not in words:
        raise RuntimeError('Guest booted an unexpected slot/version')


def run(timeout, rootfs_override=None, data_image=None, expected_slot=None, expected_version=None):
    kernel = IMAGES / 'Image'
    rootfs = Path(rootfs_override) if rootfs_override else IMAGES / 'rootfs.ext4'
    qemu = QEMU_HOST if QEMU_HOST.exists() else shutil.which('qemu-system-aarch64')
    if not kernel.is_file() or not rootfs.is_file() or (rootfs.is_symlink() and rootfs_override):
        raise RuntimeError('Kernel/rootfs image missing: run ./scripts/build-and-test.sh first')
    if not qemu:
        raise RuntimeError('qemu-system-aarch64 missing (Buildroot host tool or system package)')

    if expected_slot is not None and (expected_slot not in ('A', 'B') or not expected_version):
        raise ValueError('slot validation requires a slot and version')
    if data_image is not None and (not Path(data_image).is_file() or Path(data_image).is_symlink()):
        raise ValueError('persistent data source must be a regular file')

    with tempfile.TemporaryDirectory(prefix='virtualedge-qemu-') as directory:
        disk = Path(directory) / 'test-rootfs.ext4'
        shutil.copyfile(rootfs.resolve(), disk)
        data_disk = None
        if data_image is not None:
            data_disk = Path(directory) / 'test-data.ext4'
            shutil.copyfile(data_image, data_disk)
        master, slave = pty.openpty()
        command = [str(qemu), '-M', 'virt', '-cpu', 'cortex-a53', '-smp', '1',
                   '-m', '256', '-nographic', '-monitor', 'none', '-serial', 'stdio',
                   '-kernel', str(kernel), '-append', ('rootwait root=/dev/vda console=ttyAMA0' +
                       (f' ve.slot={expected_slot} ve.version={expected_version}' if expected_slot else '')),
                   '-netdev', 'user,id=eth0', '-device', 'virtio-net-device,netdev=eth0',
                   ]
        if data_disk is not None:
            # The virt MMIO disk probe order is reversed in the QEMU setup used here.
            # Attach data first so Linux exposes the root disk as /dev/vda.
            command += ['-drive', f'file={data_disk},if=none,format=raw,id=data',
                        '-device', 'virtio-blk-device,drive=data']
        command += ['-drive', f'file={disk},if=none,format=raw,id=hd0',
                    '-device', 'virtio-blk-device,drive=hd0']
        proc = subprocess.Popen(command, stdin=slave, stdout=slave, stderr=slave,
                                close_fds=True, start_new_session=True)
        os.close(slave)
        output = bytearray()
        end = time.monotonic() + timeout
        logged_in = False
        sent_test = False
        checked_slot = expected_slot is None
        slot_command_sent = False
        try:
            while time.monotonic() < end:
                if proc.poll() is not None:
                    raise RuntimeError(f'QEMU exited early with code {proc.returncode}')
                readable, _, _ = select.select([master], [], [], 0.4)
                if not readable:
                    continue
                try:
                    data = os.read(master, 8192)
                except OSError as error:
                    if error.errno == errno.EIO:
                        break
                    raise
                if not data:
                    break
                sys.stdout.buffer.write(data)
                sys.stdout.buffer.flush()
                output += data
                if len(output) > 160_000:
                    del output[:len(output) - 80_000]
                normalized = output.decode('utf-8', errors='replace').replace('\r', '')
                check_boot_failure(normalized)
                if not logged_in and re.search(r'(?:buildroot|virtualedge) login:\s*$', normalized):
                    os.write(master, b'root\n')
                    logged_in = True
                if logged_in and not checked_slot:
                    if not slot_command_sent and re.search(r'(?:\r?\n)#\s*$', normalized):
                        os.write(master, b'cat /proc/cmdline; echo __VE_CMDLINE_END__\n')
                        slot_command_sent = True
                    marker = re.search(r'(?m)^__VE_CMDLINE_END__\n', normalized) if slot_command_sent else None
                    if marker:
                        # Ignore the echoed shell command, and preserve the next
                        # prompt if it arrived in the same serial read as the marker.
                        evidence = normalized.split('cat /proc/cmdline; echo __VE_CMDLINE_END__', 1)[-1]
                        verify_cmdline(evidence.split('\n__VE_CMDLINE_END__', 1)[0], expected_slot, expected_version)
                        checked_slot = True
                        # Keep the newline that anchors the next shell prompt.
                        normalized = normalized[marker.end() - 1:]
                        output[:] = normalized.encode('utf-8')
                if logged_in and checked_slot and not sent_test and re.search(r'(?:\r?\n)#\s*$', normalized):
                    os.write(master, b'virtualedge-selftest; echo __VE_TEST_RC__$?\n')
                    sent_test = True
                if sent_test:
                    match = re.search(r'__VE_TEST_RC__(\d+)\n', normalized)
                    if match:
                        if match.group(1) != '0' or 'PASS: VirtualEdge QEMU guest service' not in normalized:
                            raise RuntimeError('Guest self-test failed; examine QEMU output')
                        print('\nPASS: Automated QEMU ARM64 boot and guest API self-test', flush=True)
                        return
            raise TimeoutError(f'QEMU did not pass self-test within {timeout} seconds')
        finally:
            try:
                os.write(master, b'poweroff\n')
            except OSError:
                pass
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                os.killpg(proc.pid, signal.SIGTERM)
                try:
                    proc.wait(timeout=3)
                except subprocess.TimeoutExpired:
                    os.killpg(proc.pid, signal.SIGKILL)
                    proc.wait()
            os.close(master)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--timeout', type=int, default=180)
    parser.add_argument('--rootfs', type=Path, help='Alternative QEMU rootfs; always copied to temporary disk')
    parser.add_argument('--data-image', type=Path, help='Persistent data disk; always copied to temporary disk')
    parser.add_argument('--expected-slot', choices=['A', 'B'])
    parser.add_argument('--expected-version')
    arguments = parser.parse_args()
    try:
        if bool(arguments.expected_slot) != bool(arguments.expected_version):
            parser.error('--expected-slot and --expected-version must be used together')
        run(arguments.timeout, arguments.rootfs, arguments.data_image,
            arguments.expected_slot, arguments.expected_version)
    except (RuntimeError, TimeoutError, OSError, ValueError) as exc:
        print(f'FAIL: {exc}', file=sys.stderr)
        sys.exit(1)
